"""Generate the quality/weak variants from the final reference planner.

Each variant is the reference ``method/rt_lacam.py`` with one documented edit,
so every comparison isolates that edit. Run after any change to the reference.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CASES = Path(__file__).resolve().parent / "cases"
REF = (ROOT / "method" / "rt_lacam.py").read_text()


def patch(src, old, new):
    assert src.count(old) == 1, old
    return src.replace(old, new)


variants = {}

# Better: allow legal priority-inheritance rotations (cycles of length >= 3).
variants["q_rotations"] = patch(REF, """            if agent in visiting:
                return False
            visiting.add(agent)""", """            if agent in visiting:
                return True
            visiting.add(agent)""")

# Honest alternative: restore reservations after a failed recursive branch.
variants["q_backtrack_fix"] = patch(REF, """                if displaced is not None and displaced != agent and displaced not in assigned:
                    if not assign(displaced):
                        continue
                    if target in used or edge_conflicts(agent, target):
                        continue""", """                if displaced is not None and displaced != agent and displaced not in assigned:
                    assigned_before = dict(assigned)
                    used_before = set(used)
                    if not assign(displaced):
                        assigned.clear(); assigned.update(assigned_before)
                        used.clear(); used.update(used_before)
                        continue
                    if target in used or edge_conflicts(agent, target):
                        assigned.clear(); assigned.update(assigned_before)
                        used.clear(); used.update(used_before)
                        continue""")

# Honest alternative: avoid other agents' goal cells on distance ties.
variants["q_goal_traffic"] = patch(REF, """        return sorted(self.nbrs[cell], key=lambda c: (dist.get(c, 10**6), c != cell, c))""",
    """        goals = self.goals
        return sorted(self.nbrs[cell], key=lambda c: (dist.get(c, 10**6), sum(c == g for j, g in enumerate(goals) if j != agent), c != cell, c))""")

# Weaker: forget the search after every executed move (naive restart).
variants["w_no_memory"] = patch(REF, """    def step(self, config, clock):
        solver = self.solver
        solver.advance(clock)""", """    def step(self, config, clock):
        solver = self.solver = LazyLaCAM(self.instance, start=config)
        solver.advance(clock)""").replace("""    def __init__(self, instance: dict):
        self.solver = LazyLaCAM(instance)""", """    def __init__(self, instance: dict):
        self.instance = instance
        self.solver = LazyLaCAM(instance)""")

# Weaker: execute a single planned move, then stop planning (wait forever).
variants["w_limited_steps"] = patch(REF, """    def step(self, config, clock):
        solver = self.solver
        solver.advance(clock)""", """    def step(self, config, clock):
        solver = self.solver
        if getattr(self, "_moved", False):
            return config
        solver.advance(clock)""").replace("""        solver.reroot_to_child(nxt)
        return nxt""", """        solver.reroot_to_child(nxt)
        self._moved = True
        return nxt""")

for name, src in variants.items():
    # A comment, not a docstring: nothing may precede the module's own
    # docstring and its ``from __future__`` import.
    header = f"# Hardening case {name}: generated by redteam/hardened/make_cases.py.\n"
    (CASES / f"{name}.py").write_text(header + src)
    print("wrote", name)
